// No package install needed. Assemble the existing vanilla JS in upstream order.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { restoreAssets } from './restore-assets.mjs';
restoreAssets();
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');

// Compile the editable UI translations. Species/move/item names in this map
// come from the upstream PokéAPI CSV dataset (Traditional Chinese language 4).
let english;
vm.runInNewContext(read('js/data/lang-en.js'), { G: { I18n: { lang: 'en', add: d => { english = d; } } } });
const chinese = JSON.parse(read('tools/zh-Hant-ui.json'));
const phrases = Object.fromEntries(Object.entries(english).map(([es, en]) => [es, chinese[en] || en]));
Object.assign(phrases, chinese, {
  Kanto: '關都', Johto: '城都', Hoenn: '豐緣', Sinnoh: '神奧', Teselia: '合眾', Unova: '合眾',
  Kalos: '卡洛斯', Alola: '阿羅拉', Galar: '伽勒爾', Paldea: '帕底亞',
  valiente: '勇敢', impulsivo: '衝動', prudente: '謹慎', leal: '忠誠', paciente: '耐心',
  dulce: '溫柔', tímido: '害羞', travieso: '調皮', sereno: '沉著', astuto: '機靈',
  alegre: '開朗', tenaz: '堅毅', orgulloso: '自信', solitario: '獨立', tranquilo: '悠閒', caótico: '隨興',
  nivel: '等級', niveles: '級', 'Buscar por nombre': '搜尋名稱', 'Nº': '編號',
  'Pokémonedas': '金幣', Gacha: '招募夥伴', Recarga: '冷卻時間',
  tiempo: '時間', derrotados: '擊敗數', jefes: '首領', recogidas: '拾取',
  '¡Un objeto!': '發現攜帶道具！', 'Cuántos efectos y partículas se dibujan.': '畫面上的特效與粒子數量。'
});
for (const [k, v] of Object.entries(phrases)) if (/^[a-záéíóúñ]/.test(k)) {
  const cap = k[0].toUpperCase() + k.slice(1);
  if (!phrases[cap]) phrases[cap] = v;
}
fs.writeFileSync(path.join(root, 'js/data/lang-zh-Hant.js'),
  '/* Generated by tools/build-solo.mjs; edit tools/zh-Hant-ui.json. */\n' +
  "if (G.I18n.lang === 'zh-Hant') G.I18n.add(" + JSON.stringify(phrases, null, 2) + ');\n');

const html = read('dev.html');
const block = html.match(/<!-- scripts:begin -->[\s\S]*?<!-- scripts:end -->/)[0];
const scripts = [...block.matchAll(/src="(js\/[^"?]+\.js)"/g)].map(m => m[1]);
const bundle = scripts.map(p => `/* ${p} */\n${read(p)}\n;`).join('\n');
const hash = crypto.createHash('sha256').update(bundle).digest('hex').slice(0, 12);
const dist = path.join(root, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, 'js'), { recursive: true });
for (const p of ['assets', 'css', 'manifest.webmanifest', 'favicon.ico', 'LICENSE', 'CREDITS.md', 'sw.js'])
  fs.cpSync(path.join(root, p), path.join(dist, p), { recursive: true });
fs.writeFileSync(path.join(dist, 'js/game.bundle.js'), bundle);
fs.writeFileSync(path.join(dist, 'index.html'), html.replace(block,
  `<script defer src="js/game.bundle.js?v=${hash}"></script>`));
// Keep the legacy root entry on this same single-player build.
fs.writeFileSync(path.join(root, 'js/app.min.js'), bundle);
fs.writeFileSync(path.join(root, 'index.html'), html.replace(block,
  `<script defer src="js/app.min.js?v=${hash}"></script>`));
console.log(JSON.stringify({ scripts: scripts.length, bundleBytes: Buffer.byteLength(bundle), revision: hash, output: dist }));
